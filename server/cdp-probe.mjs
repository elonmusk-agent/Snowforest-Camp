import WebSocket from 'ws';
import { spawn } from 'node:child_process';
const [,, url, expr] = process.argv;
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new','--disable-gpu','--remote-debugging-port=9333','--window-size=1280,800','about:blank'], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 1500));
const list = await (await fetch('http://127.0.0.1:9333/json/list')).json();
const page = list.find(t => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
const send = (method, params) => new Promise(res => { const i = ++id; pend.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
ws.on('message', raw => { const m = JSON.parse(raw); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } });
await new Promise(r => ws.on('open', r));
await send('Page.enable');
await send('Page.navigate', { url });
await new Promise(r => setTimeout(r, 6000));
const res = await send('Runtime.evaluate', { expression: expr ?? '1+1', returnByValue: true });
console.log(JSON.stringify(res.result?.value ?? res, null, 1));
const shot = await send('Page.captureScreenshot', { format: 'png' });
if (process.argv[4]) (await import('node:fs')).writeFileSync(process.argv[4], Buffer.from(shot.data, 'base64'));
chrome.kill(); process.exit(0);
